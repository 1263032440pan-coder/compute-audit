CREATE TABLE IF NOT EXISTS audit_events (
    event_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    deepflow_instance_id VARCHAR(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin NOT NULL,
    tenant_id VARCHAR(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin NOT NULL DEFAULT '',
    raw_event_id VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin NOT NULL,
    request_start DATETIME(6) NOT NULL,
    request_end DATETIME(6) NOT NULL,
    observed_src_ip VARBINARY(16) NULL,
    destination_ip VARBINARY(16) NULL,
    observer_agent_id VARCHAR(191) NULL,
    server_pid INT UNSIGNED NULL,
    method VARCHAR(32) NOT NULL DEFAULT '',
    path VARCHAR(2048) NOT NULL DEFAULT '',
    status_code VARCHAR(32) NOT NULL DEFAULT '',
    duration_ms DOUBLE NULL,
    observation_point VARCHAR(64) NOT NULL DEFAULT '',
    normalized_sha256 BINARY(32) NOT NULL,
    received_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (event_id),
    UNIQUE KEY uq_audit_raw_event (deepflow_instance_id, tenant_id, raw_event_id),
    KEY idx_audit_request_start (request_start, event_id),
    KEY idx_audit_source_ip (observed_src_ip, request_start),
    KEY idx_audit_server_pid (observer_agent_id, server_pid, request_start),
    KEY idx_audit_status (status_code, request_start)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
